    jal   ra, draw_cube_net

    # 3. 執行 IDA* 搜尋極限狀態 (p=720, o=0)
    li    a0, 720
    li    a1, 0
    jal   ra, solve_ida

    # a0 回傳 11，正常退出
    li    a7, 10
    ecall
