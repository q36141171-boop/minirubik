# ==============================================================================
# Helper: set_pixel
# 輸入: a0 = x (0~34), a1 = y (0~24), a2 = color (0x00RRGGBB)
# 位址公式: 0xf0000000 + ((y * 35 + x) << 2)
# ==============================================================================
set_pixel:
    # t0 = y * 35 = (y << 5) + (y << 1) + y
    slli  t0, a1, 5           # y * 32
    slli  t1, a1, 1           # y * 2
    add   t0, t0, t1          # y * 34
    add   t0, t0, a1          # y * 35
    add   t0, t0, a0          # y * 35 + x
    slli  t0, t0, 2           # (y * 35 + x) * 4 bytes

    li    t1, 0xf0000000      # LED Matrix 基底位址
    add   t0, t1, t0
    sw    a2, 0(t0)
    ret

# ==============================================================================
# 清空螢幕為深灰色背景 (35x25 = 875 顆 LED)
# ==============================================================================
clear_screen:
    li    t0, 0xf0000000      # LED Matrix 基底位址
    li    t1, 875             # 35 * 25
    li    t2, 0x00202020      # 背景深灰色

# ==============================================================================
# Helper: draw_rect
# 參數: a0 = x, a1 = y, a2 = width, a3 = height, a4 = color
# ==============================================================================
draw_rect:
    addi  sp, sp, -24
    sw    ra, 20(sp)
    sw    s0, 16(sp)
    sw    s1, 12(sp)
    sw    s2, 8(sp)
    sw    s3, 4(sp)
    sw    s4, 0(sp)

    mv    s0, a0              # start_x
    mv    s1, a1              # start_y
    mv    s2, a2              # width
    mv    s3, a3              # height
    mv    s4, a4              # color

    li    t2, 0               # dy = 0
.L_rect_row_loop:
    bge   t2, s3, .L_rect_done
    li    t3, 0               # dx = 0
.L_rect_col_loop:
    bge   t3, s2, .L_rect_next_row

    add   a0, s0, t3          # x = start_x + dx
    add   a1, s1, t2          # y = start_y + dy
    mv    a2, s4              # color
    
    # 內聯 set_pixel 位址計算以提升繪製效能
    slli  t4, a1, 5
    slli  t5, a1, 1
    add   t4, t4, t5
    add   t4, t4, a1
    add   t4, t4, a0
    slli  t4, t4, 2
    li    t5, 0xf0000000
    add   t4, t5, t4
    sw    a2, 0(t4)

    addi  t3, t3, 1          # dx++
    j     .L_rect_col_loop

.L_rect_next_row:
    addi  t2, t2, 1          # dy++
    j     .L_rect_row_loop

.L_rect_done:
    lw    ra, 20(sp)
    lw    s0, 16(sp)
    lw    s1, 12(sp)
    lw    s2, 8(sp)
    lw    s3, 4(sp)
    lw    s4, 0(sp)
    addi  sp, sp, 24
    ret

# ==============================================================================
# Helper: draw_cube_net (繪製 6 個面十字展開圖)
# ==============================================================================
draw_cube_net:
    addi  sp, sp, -4
    sw    ra, 0(sp)

    # 1. U 面 (白, x=12, y=5, w=4, h=4)
    li    a0, 12
    li    a1, 5
    li    a2, 4
    li    a3, 4
    li    a4, 0x00FFFFFF
    jal   ra, draw_rect

    # 2. L 面 (橘, x=7, y=10, w=4, h=4)
    li    a0, 7
    li    a1, 10
    li    a2, 4
    li    a3, 4
    li    a4, 0x00FFA500
    jal   ra, draw_rect

    # 3. F 面 (綠, x=12, y=10, w=4, h=4)
    li    a0, 12
    li    a1, 10
    li    a2, 4
    li    a3, 4
    li    a4, 0x0000FF00
    jal   ra, draw_rect

    # 4. R 面 (紅, x=17, y=10, w=4, h=4)
    li    a0, 17
    li    a1, 10
    li    a2, 4
    li    a3, 4
    li    a4, 0x00FF0000
    jal   ra, draw_rect

    # 5. B 面 (藍, x=22, y=10, w=4, h=4)
    li    a0, 22
    li    a1, 10
    li    a2, 4
    li    a3, 4
    li    a4, 0x000000FF
